const { spawn } = require('node:child_process');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const net = require('node:net');
const assert = require('node:assert/strict');
const { chromium } = require(process.env.LARK_PLAYWRIGHT_PATH || 'playwright');

(async () => {
  const home = await fs.mkdtemp(path.join(os.tmpdir(), 'lark-scratch-test-'));
  const port = await new Promise(resolve => {
    const socket = net.createServer();
    socket.listen(0, '127.0.0.1', () => { const chosen = socket.address().port; socket.close(() => resolve(chosen)); });
  });
  const server = spawn(process.env.LARK_TEST_JAVA || 'java', ['-Duser.home=' + home, '-Dlark.ui=jar', '-jar', path.resolve(process.env.LARK_TEST_JAR || 'dist/lark.jar'), '--no-browser', '--port', String(port)], { cwd: home });
  let browser;
  try {
    await new Promise((resolve, reject) => {
      const timer = setTimeout(() => reject(new Error('Server startup timeout')), 15000);
      server.stdout.on('data', chunk => { if (chunk.toString().includes('http://127.0.0.1:')) { clearTimeout(timer); resolve(); } });
      server.once('exit', () => reject(new Error('Server exited')));
    });
    browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH, headless: process.env.LARK_HEADED !== '1' });
    const context = await browser.newContext({ viewport: { width: 1600, height: 900 } });
    const page = await context.newPage();
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    await page.goto('http://127.0.0.1:' + port);
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.locator('#outline-hide').click();
    assert.equal(await page.locator('#structure').isVisible(), false);
    await page.locator('#outline-show').click();
    assert.equal(await page.locator('#structure').isVisible(), true);
    if (await page.getByRole('button', { name: 'Later', exact: true }).isVisible()) await page.getByRole('button', { name: 'Later', exact: true }).click();
    await page.locator('#scratch').click();
    const editor = page.locator('#scratch-editor .CodeMirror');
    await editor.click();
    await page.keyboard.press('Control+A');
    await page.keyboard.type('System.out.println("detached scratch test");');
    const popupPromise = page.waitForEvent('popup');
    await page.locator('#scratch-detach').click();
    const popup = await popupPromise;
    popup.on('pageerror', error => errors.push(error.message));
    await popup.locator('#detached-editor .CodeMirror').waitFor();
    if (process.env.LARK_TEST_TOP === '1') {
      await popup.locator('#scratch-on-top').click();
      await popup.waitForFunction(() => document.querySelector('#scratch-on-top').getAttribute('aria-pressed') === 'true', null, { timeout: 15000 });
      await popup.locator('#scratch-on-top').click();
      await popup.waitForFunction(() => document.querySelector('#scratch-on-top').getAttribute('aria-pressed') === 'false', null, { timeout: 15000 });
    }
    assert.match(await popup.locator('#detached-editor').innerText(), /detached scratch test/);
    await popup.locator('#scratch-run').click();
    await popup.waitForFunction(() => document.querySelector('#scratch-output')?.textContent.includes('detached scratch test'), null, { timeout: 30000 });
    await popup.waitForFunction(() => !document.querySelector('#scratch-run').disabled);
    await popup.evaluate(() => document.querySelector('#detached-editor .CodeMirror').CodeMirror.setValue('int value = ;'));
    await popup.locator('#scratch-run').click();
    await popup.waitForFunction(() => !document.querySelector('#scratch-run').disabled, null, { timeout: 30000 });
    assert.match(await popup.locator('#scratch-output').innerText(), /error/i);
    await popup.evaluate(() => document.querySelector('#detached-editor .CodeMirror').CodeMirror.setValue('System.out.println("detached scratch test");'));
    const simultaneous = await page.evaluate(async () => {
      const start = async text => {
        const response = await fetch('/api/scratch/run', { method: 'POST', headers: { 'Content-Type': 'application/json', 'X-Lark': '1' }, body: JSON.stringify({ source: `public class ScratchPad { public static void main(String[] args) { System.out.println("${text}"); } }`, mainClass: 'ScratchPad' }) });
        if (!response.ok) throw new Error('Could not start scratch run');
        return (await response.json()).id;
      };
      const ids = await Promise.all([start('FIRST_RUN'), start('SECOND_RUN')]);
      return Promise.all(ids.map(async id => {
        for (let attempt = 0; attempt < 200; attempt++) {
          const job = await (await fetch('/api/run/' + id)).json();
          if (job.done) return job.output;
          await new Promise(resolve => setTimeout(resolve, 100));
        }
        throw new Error('Scratch run timed out');
      }));
    });
    assert.match(simultaneous[0], /FIRST_RUN/);
    assert.match(simultaneous[1], /SECOND_RUN/);
    await popup.locator('#detached-editor .CodeMirror').click();
    await popup.keyboard.press('Control+End');
    await popup.keyboard.type(' // updated');
    await popup.locator('#scratch-dock').click();
    await page.locator('#scratch-pad').waitFor({ state: 'visible' });
    assert.match(await editor.innerText(), /detached scratch test/);
    assert.match(await editor.innerText(), /updated/);
    await page.locator('#scratch-close').click();
    await page.locator('[data-welcome="new-project"]').waitFor();
    const recent = page.locator('#welcome-recent .welcome-recent-row').first();
    await recent.click();
    await page.locator('#editor .CodeMirror').waitFor({ state: 'visible' });
    await page.waitForFunction(() => document.querySelector('#editor .CodeMirror')?.CodeMirror?.getValue().includes('package app;'));
    await page.evaluate(() => document.querySelector('#editor .CodeMirror').CodeMirror.setCursor({ line: 0, ch: 0 }));
    await page.locator('#bookmark-toggle').click();
    await page.locator('#bookmark-list .bookmark-row').waitFor();
    assert.equal(await page.locator('#modal-title').innerText(), 'Name bookmark');
    await page.locator('#modal input[name="name"]').fill('First bookmark');
    await page.locator('#modal-ok').click();
    await page.getByRole('button', { name: /First bookmark/ }).waitFor();
    await page.locator('#bookmark-toggle').click();
    assert.equal(await page.locator('#bookmark-list .bookmark-row').count(), 0);
    await page.locator('#bookmark-toggle').click();
    await page.locator('#modal-cancel').click();
    assert.equal(await page.locator('#bookmark-list .bookmark-row').count(), 1, 'Cancelling naming keeps the bookmark');
    assert.equal(await page.locator('#editor .bookmark-marker').count(), 1);
    await page.locator('#update-banner').evaluate(element => { element.style.display = 'none'; });
    assert.doesNotMatch(await page.locator('#bookmark-list .bookmark-row').innerText(), /src\//);
    await page.locator('#bookmark-collapse').click();
    assert.equal(await page.locator('#bookmark-content').isVisible(), false);
    await page.locator('#bookmark-collapse').click();
    assert.equal(await page.locator('#bookmark-content').isVisible(), true);
    await page.locator('#outline-collapse').click();
    assert.equal(await page.locator('#structure-list').isVisible(), false);
    await page.locator('#outline-collapse').click();
    assert.equal(await page.locator('#structure-list').isVisible(), true);
    const tray = page.locator('#bookmark-panel');
    const beforeResize = await tray.boundingBox();
    const resizeHandle = await page.locator('[data-split="bookmarks"]').boundingBox();
    await page.mouse.move(resizeHandle.x + resizeHandle.width / 2, resizeHandle.y + resizeHandle.height / 2);
    await page.mouse.down();
    await page.mouse.move(resizeHandle.x + resizeHandle.width / 2, resizeHandle.y - 70, { steps: 8 });
    await page.mouse.up();
    const afterResize = await tray.boundingBox();
    assert(afterResize.height > beforeResize.height, 'Bookmark tray can be resized taller');
    await page.locator('#bookmark-groups').click();
    await page.locator('#modal input[name="newName"]').fill('Important');
    await page.locator('#modal-ok').click();
    await page.getByRole('button', { name: 'Rename Important' }).waitFor();
    await page.locator('#modal-cancel').click();
    await page.locator('#bookmark-list button[title="Edit bookmark"]').click();
    await page.locator('#modal input[name="name"]').fill('Main entry');
    await page.locator('#modal select[name="group"]').selectOption('Important');
    await page.locator('#modal-ok').click();
    await page.locator('#bookmark-list').getByText('Important', { exact: true }).waitFor();
    await page.locator('#bookmark-group-filter').selectOption('ungrouped');
    assert.equal(await page.locator('#bookmark-list .bookmark-row').count(), 0);
    await page.locator('#bookmark-group-filter').selectOption('group:Important');
    assert.equal(await page.locator('#bookmark-list .bookmark-row').count(), 1);
    await page.locator('#bookmark-group-filter').selectOption('all');
    await page.locator('#bookmark-groups').click();
    await page.getByRole('textbox', { name: 'Name for Important' }).fill('Reviewed');
    await page.getByRole('button', { name: 'Rename Important' }).click();
    await page.getByRole('button', { name: 'Rename Reviewed' }).waitFor();
    await page.locator('#modal-cancel').click();
    await page.locator('#bookmark-list').getByText('Reviewed', { exact: true }).waitFor();
    await page.locator('#bookmark-groups').click();
    page.once('dialog', dialog => dialog.accept());
    await page.getByRole('button', { name: 'Delete Reviewed' }).click();
    await page.getByText('No groups yet.').waitFor();
    await page.locator('#modal-cancel').click();
    await page.locator('#bookmark-list').getByText('Ungrouped', { exact: true }).waitFor();
    const sourceEditor = page.locator('#editor .CodeMirror');
    await sourceEditor.click();
    await page.keyboard.press('Control+Home');
    await page.keyboard.press('Enter');
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Main.java:2'), null, { timeout: 5000 }).catch(async error => { console.error('Bookmark state:', await page.locator('#bookmark-list').innerText(), await page.evaluate(() => JSON.stringify(Object.keys(localStorage).filter(k => k.startsWith('lark-bookmarks')).map(k => JSON.parse(localStorage[k]))))); throw error; });
    await page.keyboard.press('Control+z');
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Main.java:1'));
    await page.keyboard.press('Control+y');
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Main.java:2'));
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Main.java:2'));
    assert.deepEqual(await page.evaluate(() => document.querySelector('#editor .CodeMirror').CodeMirror._larkMinimap.bookmarks), [1]);
    await page.locator('#editor .bookmark-marker').click({ button: 'right' });
    await page.getByRole('menuitem', { name: 'Edit bookmark' }).waitFor({ timeout: 5000 }).catch(async error => { console.error('Bookmark menu:', await page.locator('#bookmark-context').evaluate(element => ({ hidden: element.hidden, display: getComputedStyle(element).display, editorMenu: document.querySelector('#editor-context').hidden, marker: document.querySelector('#editor .bookmark-marker').outerHTML }))); throw error; });
    await page.getByRole('menuitem', { name: 'Move bookmark', exact: true }).waitFor();
    await page.getByRole('menuitem', { name: 'Remove bookmark' }).waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#editor .bookmark-marker').click();
    assert.equal(await page.locator('#modal-title').innerText(), 'Edit bookmark');
    await page.locator('#modal-cancel').click();
    assert.equal(await page.locator('#editor .bookmark-marker').count(), 1, 'Clicking a marker opens details without removing it');
    await page.locator('#bookmark-scope').selectOption('file');
    await page.locator('#bookmark-next').click();
    await page.evaluate(() => {
      const editor = document.querySelector('#editor .CodeMirror').CodeMirror;
      CodeMirror.signal(editor, 'gutterClick', editor, 0, 'CodeMirror-linenumbers', { button: 0 });
    });
    assert.equal(await page.locator('#editor .cm-breakpoint').count(), 1, 'Breakpoint gutter remains usable');
    assert.equal(await page.locator('#editor .bookmark-marker').count(), 1, 'Breakpoint does not remove bookmark');
    await page.evaluate(() => {
      const key = Object.keys(localStorage).find(key => key.startsWith('lark-bookmarks-v1:') && !key.endsWith(':groups'));
      const saved = JSON.parse(localStorage.getItem(key));
      saved.items[0].anchor.text = 'missing original code';
      localStorage.setItem(key, JSON.stringify(saved));
    });
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.getByText(/Location needs review/).waitFor();
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    assert.match(await page.locator('#modal-note').innerText(), /missing original code/);
    await page.locator('#modal input[name="line"]').fill('2');
    await page.locator('#modal-ok').click();
    await page.locator('#editor .bookmark-marker').waitFor();
    assert.match(await page.locator('#bookmark-list').innerText(), /Main entry/);
    await page.locator('.tree-row[data-path="src/app/Main.java"]').click({ button: 'right' });
    await page.locator('#context').getByRole('button', { name: 'Rename', exact: true }).click();
    await page.locator('#modal input[name="path"]').fill('src/app/Renamed.java');
    await page.locator('#modal-ok').click();
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Renamed.java:2'));
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Renamed.java:2'));
    await page.getByRole('button', { name: /Main entry/ }).click();
    await page.locator('#editor .bookmark-marker').waitFor();
    const projectDirectory = await page.evaluate(async () => {
      const id = decodeURIComponent(location.hash.slice(1));
      return (await (await fetch('/api/projects/' + encodeURIComponent(id))).json()).project.path;
    });
    const editedFile = path.join(projectDirectory, 'src', 'app', 'Renamed.java');
    const sourceBeforeExternalEdit = await fs.readFile(editedFile, 'utf8');
    await fs.writeFile(editedFile, '// external insertion\n' + sourceBeforeExternalEdit, 'utf8');
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('Renamed.java:3'));
    await fs.writeFile(editedFile, ('// external insertion\n' + sourceBeforeExternalEdit).replace('package app;', '// removed original code'), 'utf8');
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.getByText(/Location needs review/).waitFor();
    await page.getByRole('button', { name: 'Review', exact: true }).click();
    await page.locator('#modal input[name="line"]').fill('2');
    await page.locator('#modal-ok').click();
    await page.locator('#editor .bookmark-marker').waitFor();
    await page.locator('.tree-row[data-path="src/app"]').click({ button: 'right' });
    await page.locator('#context').getByRole('button', { name: 'Rename', exact: true }).click();
    await page.locator('#modal input[name="path"]').fill('src/app2');
    await page.locator('#modal-ok').click();
    await page.waitForFunction(() => document.querySelector('#bookmark-list')?.textContent.includes('app2/Renamed.java:2'), null, { timeout: 5000 }).catch(async error => { console.error('Folder move:', await page.locator('#bookmark-list').innerText(), await page.locator('#toasts').innerText()); throw error; });
    await page.reload();
    await page.locator('#boot').waitFor({ state: 'hidden' });
    await page.getByRole('button', { name: /Main entry/ }).click();
    await page.locator('#editor .bookmark-marker').waitFor();
    await page.locator('.tree-row[data-path="src/app2/Renamed.java"]').click({ button: 'right' });
    await page.locator('#context').getByRole('button', { name: 'Delete', exact: true }).click();
    await page.locator('#modal-ok').click();
    await page.getByText(/Location needs review/).waitFor();
    await page.locator('.tree-row[data-path="src/library/Book.java"]').click();
    await page.locator('#editor .CodeMirror').click();
    await page.keyboard.press('Escape');
    await page.locator('#project-search').focus();
    await page.keyboard.press('Control+p');
    await page.locator('#palette-input').fill('Bookmarks: Next bookmark');
    await page.getByRole('button', { name: /Bookmarks: Next bookmark/ }).waitFor();
    await page.keyboard.press('Escape');
    await page.locator('#scratch').click();
    const recoveryPopupPromise = page.waitForEvent('popup');
    await page.locator('#scratch-detach').click();
    const recoveryPopup = await recoveryPopupPromise;
    await recoveryPopup.locator('#detached-editor .CodeMirror').waitFor();
    await page.close();
    await recoveryPopup.evaluate(() => document.querySelector('#detached-editor .CodeMirror').CodeMirror.setValue('Recovered after main window close'));
    await recoveryPopup.waitForFunction(() => document.querySelector('#scratch-save').textContent === 'Saved locally');
    const reopened = await recoveryPopup.context().newPage();
    await reopened.goto('http://127.0.0.1:' + port);
    await reopened.locator('#boot').waitFor({ state: 'hidden' });
    if (await reopened.getByRole('button', { name: 'Later', exact: true }).isVisible()) await reopened.getByRole('button', { name: 'Later', exact: true }).click();
    await reopened.locator('#scratch').click();
    await reopened.getByText('This Scratch pad is open in another window.').waitFor();
    assert.equal(await reopened.locator('#scratch-pad').isVisible(), false);
    await recoveryPopup.close();
    await reopened.waitForFunction(async () => !(await navigator.locks.query()).held.some(lock => lock.name.startsWith('lark-scratch:')));
    await reopened.locator('#scratch').click();
    await reopened.locator('#scratch-editor .CodeMirror').waitFor();
    assert.match(await reopened.locator('#scratch-editor').innerText(), /Recovered after main window close/);
    await reopened.locator('#scratch-close').click();
    await reopened.evaluate((restoreOnTop) => {
      const deck = JSON.parse(localStorage.getItem('lark-scratch-deck-v1'));
      const item = deck.items[deck.active];
      item.detached = true;
      item.alwaysOnTop = restoreOnTop;
      item.updatedAt = Date.now() + 10;
      localStorage.setItem('lark-scratch-deck-v1', JSON.stringify(deck));
      localStorage.setItem('lark-scratch-restore-windows', '1');
    }, process.env.LARK_TEST_TOP === '1');
    const restoredWindowPromise = reopened.waitForEvent('popup', { timeout: 15000 });
    await reopened.reload();
    const restoredWindow = await restoredWindowPromise;
    await restoredWindow.locator('#detached-editor .CodeMirror').waitFor();
    assert.match(await restoredWindow.locator('#detached-editor').innerText(), /Recovered after main window close/);
    if (process.env.LARK_TEST_TOP === '1') {
      await restoredWindow.waitForFunction(() => document.querySelector('#scratch-on-top').getAttribute('aria-pressed') === 'true', null, { timeout: 15000 });
      await restoredWindow.locator('#scratch-on-top').click();
      await restoredWindow.waitForFunction(() => document.querySelector('#scratch-on-top').getAttribute('aria-pressed') === 'false', null, { timeout: 15000 });
    }
    await restoredWindow.locator('#scratch-dock').click();
    await reopened.locator('#scratch-pad').waitFor({ state: 'visible' });
    assert.deepEqual(errors, []);
    console.log('Scratch detach/run/dock and bookmark tracking/reload browser tests passed');
  } finally {
    if (browser) await browser.close();
    server.kill();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
